// ---- Lucide full list (lazy loaded for search) ----
// This will be populated at runtime from the lucide-vue-next module
let _lucideAllCache: string[] | null = null

export async function getLucideAllIcons(): Promise<string[]> {
  if (_lucideAllCache) return _lucideAllCache
  const mod = await import('lucide-vue-next')
  _lucideAllCache = Object.keys(mod)
    .filter(k => /^[A-Z]/.test(k) && !k.endsWith('Icon') && k !== 'default' && k !== 'createLucideIcon')
    .sort()
  return _lucideAllCache
}
